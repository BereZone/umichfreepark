#!/usr/bin/env node
/**
 * Extract only the polygons the map actually draws, into
 * src/engine/data/area-polygons.json.
 *
 * WHY NOT JUST SHIP THE RAW FILE
 *
 * data/raw/osm-parking.geojson is 2 MB and holds 1,646 features, of which 73
 * are areas CURB models. The rest are private residential and business lots
 * that exist only so hand-tagging can select from them. Bundling all of it
 * would put 2 MB into an app whose entire premise is working offline on a
 * phone, to draw 4% of it.
 *
 * It also cannot be imported directly: bundlers do not treat `.geojson` as
 * JSON, and renaming the raw file would obscure what it is.
 *
 * This step stays dumb on purpose. It copies rings verbatim and does NOT
 * normalize winding or compute label points — those live in src/geo, are
 * unit-tested there, and would otherwise exist in two implementations that
 * could disagree.
 *
 * Usage:
 *   node scripts/build-area-polygons.mjs [--dry-run]
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(path.join(ROOT, p), 'utf8'));
const OUT = 'src/engine/data/area-polygons.json';

/** Coordinate precision. ~1 cm at this latitude, far finer than a lot boundary. */
const DECIMALS = 6;
const round = (n) => Number(n.toFixed(DECIMALS));

/** The city areas, mirroring src/engine/data/city-areas.ts. */
const CITY_OSM_IDS = {
  'ann-ashley': 'way/30838959',
  'fourth-washington': 'way/30839085',
  'fourth-william': 'way/30839105',
  'library-lane': 'way/30839120',
  maynard: 'way/30839161',
  'liberty-square': 'way/30839192',
  forest: 'way/30839268',
  'south-ashley-lot': 'way/30839328',
  'first-william-lot': 'way/495081613',
};

function ringsFor(feature) {
  if (feature.geometry.type === 'Polygon') return feature.geometry.coordinates;
  // Largest part of a multipolygon; the rest are slivers too small to tap.
  const parts = feature.geometry.coordinates;
  const area = (rings) => {
    let sum = 0;
    const ring = rings[0];
    for (let i = 0; i < ring.length; i++) {
      const [x1, y1] = ring[i];
      const [x2, y2] = ring[(i + 1) % ring.length];
      sum += (x2 - x1) * (y2 + y1);
    }
    return Math.abs(sum / 2);
  };
  return parts.reduce((best, part) => (area(part) > area(best) ? part : best), parts[0]);
}

function main() {
  const dryRun = process.argv.includes('--dry-run');
  const geo = read('data/raw/osm-parking.geojson');
  const umich = read('src/engine/data/umich-areas.json');

  const wanted = new Map(Object.entries(CITY_OSM_IDS));
  // Only lots that actually have a polygon. The rest ship as list-only areas.
  for (const a of umich.areas) if (a.osmId) wanted.set(a.id, a.osmId);

  const byOsmId = new Map(geo.features.map((f) => [f.properties.osm_id, f]));

  const polygons = {};
  const missing = [];
  let coordinateCount = 0;

  for (const [id, osmId] of wanted) {
    const feature = byOsmId.get(osmId);
    if (!feature) {
      missing.push(`${id} -> ${osmId}`);
      continue;
    }
    const rings = ringsFor(feature).map((ring) =>
      ring.map(([lon, lat]) => [round(lon), round(lat)])
    );
    coordinateCount += rings.reduce((n, r) => n + r.length, 0);
    polygons[id] = { osmId, rings };
  }

  console.log(`${Object.keys(polygons).length} areas, ${coordinateCount} coordinates.`);
  if (missing.length) {
    console.log(`MISSING ${missing.length}:`);
    for (const m of missing) console.log(`  ${m}`);
  }

  const out = {
    _comment:
      'Generated by scripts/build-area-polygons.mjs from data/raw/osm-parking.geojson. Do not hand-edit.',
    license: 'OpenStreetMap contributors, ODbL. https://www.openstreetmap.org/copyright',
    generatedAt: new Date().toISOString().slice(0, 10),
    note: 'Rings are verbatim from OSM: winding is NOT normalized and label points are NOT computed here. Both happen in src/geo, which is unit-tested.',
    polygons,
  };

  const json = `${JSON.stringify(out)}\n`;
  console.log(`${(json.length / 1024).toFixed(1)} KB`);
  if (dryRun) {
    console.log('--dry-run: nothing written.');
    return;
  }
  writeFileSync(path.join(ROOT, OUT), json, 'utf8');
  console.log(`Wrote ${OUT}`);
}

main();
